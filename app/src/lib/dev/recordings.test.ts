// The recordings of the decode bench (recordings.ts) must be the subscribe recordings of
// efrd (test/recordings/*.ndjson), line for line. `just bless` writes the recordings
// again; then write recordings.ts again with
//
//   EFR_WRITE_DEV_RECORDINGS=1 pnpm vitest run src/lib/dev/recordings.test.ts
//   pnpm fmt

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { describe, expect, it } from "vitest";

import { RECORDINGS, type Recording } from "./recordings";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const DIR = path.join(HERE, "../../../test/recordings");

/** The recordings as the files have them, sorted by name. */
function fromFiles(): Recording[] {
  return readdirSync(DIR)
    .filter((name) => name.endsWith(".ndjson"))
    .sort()
    .map((name) => ({
      name: name.slice(0, -".ndjson".length),
      lines: readFileSync(path.join(DIR, name), "utf8")
        .split("\n")
        .filter((line) => line.trim() !== ""),
    }));
}

/** The text of recordings.ts for `recordings`. */
function moduleText(recordings: readonly Recording[]): string {
  const body = recordings
    .map(
      (recording) =>
        `  {\n    name: ${JSON.stringify(recording.name)},\n    lines: [\n${recording.lines
          .map((line) => `      ${JSON.stringify(line)},`)
          .join("\n")}\n    ],\n  },`,
    )
    .join("\n");
  return [
    "// The subscribe recordings of efrd (test/recordings/*.ndjson), for the decode bench of",
    "// the dev builds (decode-bench.ts). Metro cannot import an .ndjson file, so the lines are",
    "// here as strings. Do not edit this file: recordings.test.ts checks it and writes it.",
    "",
    "/** One recording: its file name without `.ndjson`, and its lines of JSON. */",
    "export interface Recording {",
    "  readonly name: string;",
    "  readonly lines: readonly string[];",
    "}",
    "",
    "/** Every recording, sorted by name. */",
    "export const RECORDINGS: readonly Recording[] = [",
    body,
    "];",
    "",
  ].join("\n");
}

describe("the recordings of the decode bench", () => {
  it("are the recordings of efrd, line for line", () => {
    const files = fromFiles();
    if (process.env["EFR_WRITE_DEV_RECORDINGS"] === "1") {
      writeFileSync(path.join(HERE, "recordings.ts"), moduleText(files));
      return;
    }
    expect(files.length).toBe(8);
    expect(RECORDINGS).toEqual(files);
  });
});
