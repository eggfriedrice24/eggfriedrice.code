// Builds the uniwind theme (src/theme/theme.css) from the roles, the type scale and the
// metrics. scripts/gen-theme.mjs writes the result, and theme-css.test.ts fails when the
// file on disk is not what this function gives.
//
// The theme removes the default colours, text sizes, font families and radii of
// Tailwind, so a class can only name a token of the design system. It sets the spacing
// unit to 1 pt, so `p-12` is 12 pt.

import { RADII, SPACING, SPACING_UNIT } from "./metrics";
import { roles } from "./roles";
import { TYPE, type TypeStyle } from "./type";

/** `surface_1` and `monoXs` to `surface-1` and `mono-xs`. */
export function kebab(name: string): string {
  return name
    .replaceAll("_", "-")
    .replaceAll(/([a-z])([A-Z0-9])/g, "$1-$2")
    .toLowerCase();
}

const px = (points: number) => `${points}px`;

function typeUtility(name: string, style: TypeStyle): string[] {
  const lines = [`@utility text-${kebab(name)} {`];
  if (style.fontFamily !== undefined) {
    lines.push(`  font-family: ${style.fontFamily};`);
  }
  lines.push(`  font-size: ${px(style.fontSize)};`);
  if (style.lineHeight !== undefined) {
    lines.push(`  line-height: ${px(style.lineHeight)};`);
  }
  if (style.fontWeight !== undefined) {
    lines.push(`  font-weight: ${style.fontWeight};`);
  }
  lines.push("}");
  return lines;
}

/** The text of src/theme/theme.css. */
export function themeCss(): string {
  const lines = [
    "/* Generated by scripts/gen-theme.mjs from src/theme (roles.ts, type.ts, metrics.ts). */",
    "/* Do not edit this file: change those files and run `pnpm gen:theme`. */",
    "",
    "@theme {",
    "  /* Only the colour roles of roles.ts make colour classes. */",
    "  --color-*: initial;",
  ];
  for (const [name, value] of Object.entries(roles)) {
    lines.push(`  --color-${kebab(name)}: ${value};`);
  }
  lines.push(
    "",
    "  /* Only the type scale of type.ts sizes text (the text-* utilities below). */",
    "  --text-*: initial;",
    "  --font-*: initial;",
    "",
    "  /* Corners: the radii of metrics.ts, and rounded-full for circles and capsules. */",
    "  --radius-*: initial;",
  );
  for (const [name, value] of Object.entries(RADII)) {
    lines.push(`  --radius-${kebab(name)}: ${px(value)};`);
  }
  lines.push(
    "",
    "  /* One spacing step is 1 pt, and the named distances of metrics.ts. */",
    `  --spacing: ${px(SPACING_UNIT)};`,
  );
  for (const [name, value] of Object.entries(SPACING)) {
    lines.push(`  --spacing-${kebab(name)}: ${px(value)};`);
  }
  lines.push("}", "");
  for (const [name, style] of Object.entries(TYPE)) {
    lines.push(...typeUtility(name, style), "");
  }
  lines.push(
    "/* Hairlines: 0.5 pt borders. */",
    "@utility border-hairline {",
    `  border-width: ${px(SPACING.hairline)};`,
    "}",
    "",
    "@utility border-t-hairline {",
    `  border-top-width: ${px(SPACING.hairline)};`,
    "}",
    "",
    "@utility border-b-hairline {",
    `  border-bottom-width: ${px(SPACING.hairline)};`,
    "}",
    "",
  );
  return lines.join("\n");
}
